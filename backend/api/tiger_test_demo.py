def _mcq(question: str, options: list[str], correct: str) -> dict:
    answers = [
        {"answer_id": _CHOICES[i], "text": f"<p>{opt}</p>"}
        for i, opt in enumerate(options[:4])
    ]
    return {
        "question": f"<p>{question}</p>",
        "answers": answers,
        "correct": correct,
    }


