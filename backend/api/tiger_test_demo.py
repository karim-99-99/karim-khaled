def make_demo_slots(subject: str, count: int, start_index: int = 0) -> list[dict]:
    """Build `count` demo slots for verbal or quant. Cycles the bank if needed."""
    if count <= 0:
        return []
    bank = VERBAL_DEMOS if subject == "verbal" else QUANT_DEMOS
    bank_len = len(bank) or 1
    slots: list[dict] = []
    for i in range(count):
        item = bank[i % bank_len]
        n = start_index + i + 1
        question = item["question"]
        if i >= bank_len:
            question = (
                f'<p style="color:#666;font-size:13px">سؤال تجريبي رقم {n}</p>'
                + question
            )
        slots.append(
            {
                "slot_id": f"demo_{subject}_{n}_{uuid.uuid4().hex[:8]}",
                "parent_id": None,
                "passage_index": None,
                "subject": subject,
                "is_demo": True,
                "demo": {
                    "question": question,
                    "answers": item["answers"],
                    "correct": item["correct"],
                },
            }
        )
    return slots
